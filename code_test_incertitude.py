import numpy as np
import matplotlib.pyplot as plt

# PARAMETRES

n = 10000
d = 3
delta = 1e-5
test_cas = 2

#np.random.seed(0)



def M(X):

    if test_cas == 1 :
        x1 = X[:, 0]
        x2 = X[:, 1]
        x3 = X[:, 2]
    
        return -5*x1**2 - x1*x2 - 6*x1*x3 + 10*x3

    elif test_cas == 2:
         condition = (X[:, 2] <= 0.5)
        
         valeur_vrai = X[:, 0] + X[:, 2] * X[:, 1] + 10 * X[:, 0]
         valeur_faux = X[:, 0] + X[:, 2] * X[:, 1]
         
         return np.where(condition, valeur_vrai, valeur_faux)
                

# 1 - TIRAGE

X = np.random.uniform(
    0,
    1,
    size=(n, d)
)

print("Dimension de X :", X.shape)

print("\nPremiers tirages :")
print(X[:5])


# 2 - CALCUL DE M(X_k)

Y = M(X)

print("\nPremières valeurs de M(X) :")
print(Y[:5])

print("\nMoyenne de M(X) :", np.mean(Y))
print("Variance de M(X) :", np.var(Y))


# 3 - MORRIS

delta1 = np.zeros(d)
delta2 = np.zeros(d)

for i in range(d):

    X_delta = X.copy()

    X_delta[:, i] += delta



    masque = X_delta[:, i] <= 1

    X_valide = X[masque]
    X_delta_valide = X_delta[masque]

    M_X = M(X_valide)

    M_X_delta = M(X_delta_valide)

    derivee = (
        M_X_delta - M_X
    ) / delta

    delta1[i] = np.mean(
        np.abs(derivee)
    )

    delta2[i] = np.mean(
        derivee**2
    )


print("\n======================")
print("INDICES DE MORRIS")
print("======================")


#### Moyenne et variance analytique de M pour les indices de Morris

if test_cas == 1:
    M_moy_analytic = np.array([8.5, 0.5, 7])
    M_var_analytic = np.array([137/12, 1/12, 3])

elif test_cas == 2:
    M_moy_analytic = np.array([6, 0.5, 5.5])
    M_var_analytic = np.array([25, 1/12, 8])
    
####


for i in range(d):

    print(
        "X", i+1,
        ": delta1 =",
        delta1[i],
        ", delta2 =",
        delta2[i]
    )


# 4 - QUANTITE UTILISEE DANS LE GRAPHE DU COURS

# delta2 - delta1²

sigma2 = delta2 - delta1**2


plt.figure(figsize=(8,6))

list_col = ["red", "blue", "green"]

plt.scatter(
    delta1,
    sigma2,
    s=100,
    color = list_col
)

plt.scatter(M_moy_analytic, 
            M_var_analytic, 
            marker="x", 
            color = list_col)

for i in range(d):

    plt.text(
        delta1[i],
        sigma2[i],
        "  X" + str(i+1),
        fontsize=12
    )

plt.xlabel(r"$\delta_i^1$")
plt.ylabel(r"$\delta_i^2-(\delta_i^1)^2$")

plt.title("Indices de Morris")

plt.grid()

plt.show()


# 5 - TIRAGES A ET B POUR SOBOL / SALTELLI

A = np.random.uniform(
    0,
    1,
    size=(n, d)
)

B = np.random.uniform(
    0,
    1,
    size=(n, d)
)


print("\nA :")
print(A[:3])

print("\nB :")
print(B[:3])


# 6 - CONSTRUCTION DES MATRICES C_i
#


C = []

for i in range(d):

    Ci = A.copy()

    Ci[:, i] = B[:, i]

    C.append(Ci)


print("\nExemple : C1")

print(C[0][:3])


# 7 - EVALUATION DU MODELE

YA = M(A)

YB = M(B)

YC = []

for i in range(d):

    YC.append(
        M(C[i])
    )


# 8 - VARIANCE DU MODELE

V = np.var(
    np.concatenate(
        (YA, YB)
    )
)

print("\nVariance utilisée :", V)


# 9 - INDICES DE SOBOL PREMIER ORDRE
#
# Estimateur présenté dans le cours

S = np.zeros(d)

for i in range(d):

    S[i] = np.mean(
        YB * (YC[i] - YA)
    ) / V


# 10 - INDICES DE SOBOL TOTAUX

ST = np.zeros(d)

for i in range(d):

    ST[i] = np.mean(
        YA * (YA - YC[i])
    ) / V


# AFFICHAGE

print("\n======================")
print("INDICES DE SOBOL")
print("======================")

for i in range(d):

    print("\nX", i+1)

    print(
        "S =", S[i]
    )

    print(
        "Stot =", ST[i]
    )

    print(
        "Stot - S =",
        ST[i] - S[i]
    )


# GRAPHIQUE SOBOL

variables = [
    "X1",
    "X2",
    "X3"
]

x = np.arange(d)

largeur = 0.35

plt.figure(figsize=(8,6))

plt.bar(
    x - largeur/2,
    S,
    largeur,
    label="S_i"
)

plt.bar(
    x + largeur/2,
    ST,
    largeur,
    label="S_i total"
)

plt.xticks(
    x,
    variables
)

plt.ylabel(
    "Indice de Sobol"
)

plt.title(
    "Indices de Sobol"
)

plt.legend()

plt.grid(
    axis="y"
)

plt.show()

